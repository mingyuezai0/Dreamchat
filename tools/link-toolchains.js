/* link-toolchains.js — 把「仓库在哪」告诉仓库外面的打包工具链，一条命令修好所有硬编码路径
 *
 * 背景：Electron 工程（默认 D:\electron）与 Capacitor 工具链（默认 D:\Capacitor）常驻在仓库外面，
 * 它们自己不知道仓库搬到了哪里。v0.4.8 之前是把仓库绝对路径写死在脚本里，搬一次目录就静默失效。
 * 现在改成：脚本只认「环境变量 / 相对布局 / 配置文件」，本脚本负责生成那些配置文件。
 *
 *   node tools/link-toolchains.js                      # 自动探测 D:\electron 与 D:\Capacitor
 *   node tools/link-toolchains.js --electron D:\electron --capacitor D:\Capacitor
 *
 * 做两件事：
 *   1. 在 Electron 工程写 build.config.json（{ "repo": "<仓库绝对路径>" }）
 *   2. 重写 <Capacitor>\build-apk.bat 为薄委派脚本，转调 <仓库>\tools\build-apk.bat
 * 两个工具链都不存在时只打印提示，不报错（CI / 只跑测试的机器上不需要它们）。
 */
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');

function arg(name){
  const i = process.argv.indexOf('--' + name);
  return i > -1 ? process.argv[i + 1] : null;
}

const ELECTRON = arg('electron') || 'D:\\electron';
const CAPACITOR = arg('capacitor') || 'D:\\Capacitor';

function exists(p){ try{ fs.statSync(p); return true; }catch(e){ return false; } }

let did = 0;

/* ---------- 1. Electron：写 build.config.json ---------- */
if(exists(ELECTRON)){
  const cfgPath = path.join(ELECTRON, 'build.config.json');
  const cfg = {
    repo: REPO,
    _comment: '由仓库的 tools/link-toolchains.js 生成：声明「应用本体（index.html）在哪」。换仓库位置后重跑该命令即可，不要手改成本机绝对路径之外的猜测。'
  };
  fs.writeFileSync(cfgPath, JSON.stringify(cfg, null, 2) + '\n', 'utf8');
  console.log('[electron] ' + cfgPath + '  ->  repo = ' + REPO);
  did++;

  const copyJs = path.join(ELECTRON, 'scripts', 'copy-html.js');
  if(!exists(copyJs)){
    console.warn('[electron] 警告：没有 scripts/copy-html.js，npm run copy 会失败');
  }
}else{
  console.log('[electron] 跳过：' + ELECTRON + ' 不存在（要指定请用 --electron <路径>）');
}

/* ---------- 2. Capacitor：重写一个薄委派 bat ---------- */
if(exists(CAPACITOR)){
  const batPath = path.join(CAPACITOR, 'build-apk.bat');
  const lines = [
    '@echo off',
    'REM ============================================================',
    'REM  GENERATED by <repo>\\tools\\link-toolchains.js - do not edit.',
    'REM  It only delegates to the repo-side script so that the',
    'REM  project path is never hardcoded in two places.',
    'REM',
    'REM  Repo: ' + REPO,
    'REM ============================================================',
    'setlocal',
    'set "REPO=' + REPO + '"',
    'if not exist "%REPO%\\tools\\build-apk.bat" (',
    '  echo [ERROR] "%REPO%\\tools\\build-apk.bat" not found.',
    '  echo         The repo moved: run `node tools\\link-toolchains.js` again.',
    '  pause',
    '  exit /b 1',
    ')',
    'call "%REPO%\\tools\\build-apk.bat" %*',
    'exit /b %ERRORLEVEL%'
  ];
  fs.writeFileSync(batPath, lines.join('\r\n') + '\r\n', 'utf8');   // CRLF，纯 ASCII
  console.log('[capacitor] ' + batPath + '  ->  delegates to ' + path.join(REPO, 'tools', 'build-apk.bat'));
  did++;
}else{
  console.log('[capacitor] 跳过：' + CAPACITOR + ' 不存在（要指定请用 --capacitor <路径>）');
}

console.log(did ? '\nlink-toolchains: 完成 ' + did + ' 项' : '\nlink-toolchains: 没有可处理的工具链（只跑测试可以忽略）');
